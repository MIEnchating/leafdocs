import { chromium } from '@playwright/test';
import { config } from 'dotenv';
import { mkdir } from 'node:fs/promises';
config({quiet:true});
const browser=await chromium.launch({args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const base=process.env.APP_URL;
await mkdir('.data/design-preview',{recursive:true});
const snapshot=async name=>{await page.waitForLoadState('networkidle');await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:`.data/design-preview/${name}.png`,fullPage:true});};
const noOverflow=async()=>{if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Page overflow');};
await page.goto(base);await page.evaluate(()=>document.fonts.ready);await noOverflow();await snapshot('home');
await page.getByRole('button',{name:'切换主题'}).click();
await page.getByRole('button',{name:'浅石 冷灰与留白'}).click();
await page.reload();
await page.waitForFunction(()=>document.documentElement.dataset.theme==='stone');
await page.getByRole('button',{name:'切换主题'}).click();
await page.getByRole('button',{name:'纸白 白纸与黑墨'}).click();
await page.getByRole('button',{name:'关闭主题选择'}).click();
await page.getByRole('button',{name:/搜索文档/}).click();
await page.getByRole('textbox',{name:'搜索文档'}).fill('令牌');
await page.locator('.search-results a').first().waitFor();
await page.getByRole('button',{name:'关闭搜索'}).click();
await page.goto(base+'/docs/first-request');await page.locator('.rs-line-number').first().waitFor();await noOverflow();await snapshot('reader');
await page.setViewportSize({width:390,height:844});await noOverflow();await snapshot('reader-mobile');
await page.goto(base);await noOverflow();await snapshot('home-mobile');
await page.getByRole('button',{name:'打开文档目录'}).click();await page.getByRole('button',{name:'搜索文档… ⌘ K'}).waitFor();
await page.goto(base+'/login');await noOverflow();await snapshot('login-mobile');
await page.setViewportSize({width:1440,height:1000});await snapshot('login');
// Credentials are never captured in screenshots or request traces.
await page.getByLabel('邮箱地址').fill(process.env.ADMIN_EMAIL);
await page.getByLabel('密码',{exact:true}).fill(process.env.ADMIN_PASSWORD);
await page.getByRole('button',{name:'进入工作台'}).click();await page.waitForURL('**/admin');
await page.locator('.bn-editor').first().waitFor();await noOverflow();await snapshot('workspace');
await page.getByRole('button',{name:'页面设置',exact:true}).click();
await page.getByLabel('文档图标').waitFor();
await page.getByRole('button',{name:'页面设置',exact:true}).click();
await page.getByRole('button',{name:'预览',exact:true}).click();
await page.getByRole('dialog',{name:'草稿预览'}).waitFor();
await page.getByRole('button',{name:'关闭预览'}).click();
await page.setViewportSize({width:390,height:844});await noOverflow();await snapshot('workspace-mobile');
await browser.close();
if(errors.length)throw Error(errors.join('\n'));
console.log('Desktop/mobile layouts, theme persistence, search, login, editor settings and preview verified.');
